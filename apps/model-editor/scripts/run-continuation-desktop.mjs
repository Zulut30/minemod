import assert from "node:assert/strict";
import {readFile,mkdir} from "node:fs/promises";
import {join} from "node:path";
import {fileURLToPath,URL} from "node:url";
import {randomUUID} from "node:crypto";
import process from "node:process";
import console from "node:console";
import {checkContinuationDesktop} from "./check-continuation-desktop.mjs";
const repo=fileURLToPath(new URL("../../../",import.meta.url));
const build=JSON.parse(await readFile(join(repo,"output/model-editor/latest-build.json"),"utf8")),pkg=JSON.parse(await readFile(new URL("../package.json",import.meta.url),"utf8"));assert.equal(build.version,pkg.version);
const output=join(repo,"output/playwright/continuation-039-"+randomUUID().slice(0,8));await mkdir(output);
const report=await checkContinuationDesktop({executablePath:build.executable,args:["--editor-hidden"],env:Object.fromEntries(Object.entries(process.env).filter(([k,v])=>k!=="ELECTRON_RUN_AS_NODE"&&typeof v==="string")),timeout:45000},output);
console.log(JSON.stringify({status:report.status,output,pauseMs:report.pauseMs,studioVersion:build.version}));
